/* 展平：全省市列表（搜索用） */
function flattenAll() {
  const out = [];
  PROVINCES.forEach((p) => {
    (p.cities || []).forEach((c) => out.push({ province: p.name, city: c, full: p.name + '·' + c }));
  });
  return out;
}

let _flatCache = null;
function allCities() {
  if (!_flatCache) _flatCache = flattenAll();
  return _flatCache;
}

/* 名称归一：去掉「省/市/区/县/自治区/特别行政区/自治州/自治县/地区/盟」后缀再比对
 * （兼容存量自由文本如「广东省·广州市」「北京市 · 东城区」） */
function _norm(name) {
  return String(name || '')
    .replace(/(维吾尔|壮族|回族|哈萨克族|柯尔克孜族|蒙古族|藏族|苗族|彝族|傣族|傈僳族|朝鲜族|土家族|布依族|侗族|哈尼族|黎族)/g, '')
    .replace(/(省|市|区|县|自治区|特别行政区|自治州|自治县|地区|盟|土家族苗族自治州|布依族苗族自治州|傣族景颇族自治州|藏族自治州|彝族自治州|哈尼族彝族自治州|壮族苗族自治州|苗族侗族自治州|傈僳族自治州|蒙古自治州|回族自治州|柯尔克孜自治州|哈萨克自治州|朝鲜族自治州|黎族苗族自治县|黎族自治县|苗族土家族自治县|土家族自治县|侗族自治县)/g, '')
    .trim();
}

/* 搜索：城市名或省名包含 keyword（去后缀容错，空串返回空） */
function search(keyword) {
  const kw = _norm(keyword);
  if (!kw) return [];
  return allCities().filter((it) => _norm(it.city).indexOf(kw) !== -1 || it.province.indexOf(kw) !== -1);
}

/* 解析存量值（可能为「省·市」或纯城市名或自由文本）：
 * 命中数据集 → { province, city, full, matched: true }；未命中 → { full: 原文, matched: false } */
function parseValue(value) {
  const v = String(value || '').trim();
  if (!v) return null;
  if (v.indexOf('·') !== -1) {
    const parts = v.split('·');
    const prov = parts[0].trim();
    const city = (parts[1] || '').trim();
    const p = PROVINCES.find((it) => it.name === prov || _norm(it.name) === _norm(prov));
    if (p && city && p.cities.some((c) => c === city || _norm(c) === _norm(city))) {
      const cityName = p.cities.find((c) => c === city || _norm(c) === _norm(city));
      return { province: p.name, city: cityName, full: v, matched: true };
    }
    return { full: v, matched: false };
  }
  const hit = allCities().find((it) => it.city === v || _norm(it.city) === _norm(v));
  if (hit) return Object.assign({ matched: true }, hit);
  // 纯省名（如「北京」「广东」）→ 省命中（城市留空）
  const provHit = PROVINCES.find((it) => it.name === v || _norm(it.name) === _norm(v));
  if (provHit) return { province: provHit.name, city: '', full: v, matched: true };
  return { full: v, matched: false };
}

