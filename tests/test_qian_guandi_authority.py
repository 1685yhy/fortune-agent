def _norm_jie(s: str) -> str:
    s = re.sub(r"[。，、？！：；·—…「」『』（）()“”\s]", "", s)
    return "".join(_JIE_VAR.get(ch, ch) for ch in s)


def _poem_diffs(ours, wiki):
    """签诗逐字差异：[(行号1起, [(字位0起, 我方, 维基)...])...]"""
    out = []
    for i in range(4):
        if ours[i] != wiki[i]:
            d = [(j, ours[i][j], wiki[i][j])
                 for j in range(len(ours[i])) if ours[i][j] != wiki[i][j]]
            out.append((i + 1, d))
    return out


